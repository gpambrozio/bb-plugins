#!/usr/bin/env node
// Writes app/icon-names.ts: every icon name bb's host Icon can draw, read out of bb's own app bundle.
//
// The SDK types an icon name as a plain string and draws a generic bolt for a name it does not know, and
// it exports no list of names, so the list comes from the bundle. There, the icon module exports
// `ICON_NAMES`, built as `[...Object.keys(<registry>), ...<lazy names>]`: an object of eagerly bundled
// icons and a backtick string of lazily loaded ones, split on ".". This finds both by that shape, not by
// their minified names.
//
//   npm run icon-names                       # from the installed bb.app
//   npm run icon-names -- <bundle.js> [<bb version>]
//
// Rerun after a bb update and commit the result; `app/icons.test.ts` checks it.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const BB_APP = "/Applications/bb.app/Contents/Resources/app.asar.unpacked/node_modules/bb-app";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "app", "icon-names.ts");

function fail(message) {
  console.error(`icon-names: ${message}`);
  process.exit(1);
}

function defaultBundle() {
  const assets = join(BB_APP, "app", "dist", "assets");
  const candidates = readdirSync(assets).filter((name) => /^index-.*\.js$/.test(name));
  const bundle = candidates.map((name) => join(assets, name)).find((path) => readFileSync(path, "utf8").includes("ICON_NAMES:"));
  if (bundle === undefined) fail(`no index-*.js in ${assets} exports ICON_NAMES`);
  return bundle;
}

const escape = (name) => name.replace(/[$]/g, "\\$");

/** The keys of the object literal that starts at `start` (its `{`): identifiers before a `:` at depth 1. */
function objectKeys(source, start) {
  const keys = [];
  let depth = 0;
  let expectKey = false;
  for (let i = start; i < source.length; i++) {
    const char = source[i];
    if (char === "`" || char === '"' || char === "'") {
      // Skip a string. The registry's strings are SVG attributes, with no `${` inside.
      const end = source.indexOf(char, i + 1);
      if (end < 0) fail("unterminated string in the icon registry");
      i = end;
      expectKey = false;
      continue;
    }
    if (char === "{" || char === "[" || char === "(") {
      depth++;
      if (depth === 1) expectKey = true;
      continue;
    }
    if (char === "}" || char === "]" || char === ")") {
      depth--;
      if (depth === 0) return keys;
      continue;
    }
    if (depth === 1 && char === ",") {
      expectKey = true;
      continue;
    }
    if (depth === 1 && expectKey) {
      const match = /^([A-Za-z_$][\w$]*):/.exec(source.slice(i, i + 80));
      if (match === null) fail(`expected a key in the icon registry at offset ${i}`);
      keys.push(match[1]);
      i += match[1].length;
      expectKey = false;
    }
  }
  fail("the icon registry never closes");
}

export function iconNames(source) {
  const exported = /ICON_NAMES:\(\)=>([\w$]+)/.exec(source);
  if (exported === null) fail("no ICON_NAMES export");
  const list = new RegExp(`[,;\\s]${escape(exported[1])}=\\[\\.\\.\\.Object\\.keys\\(([\\w$]+)\\),\\.\\.\\.([\\w$]+)\\]`).exec(source);
  if (list === null) fail(`ICON_NAMES (${exported[1]}) is no longer [...Object.keys(registry), ...lazy]`);
  const [, registry, lazy] = list;
  const registryAt = new RegExp(`[,;\\s]${escape(registry)}=\\{`).exec(source);
  if (registryAt === null) fail(`no object literal for the icon registry (${registry})`);
  const eager = objectKeys(source, registryAt.index + registryAt[0].length - 1);
  const lazyAt = new RegExp(`[,;\\s]${escape(lazy)}=\`([A-Za-z0-9.]*)\`\\.split\\(\`\\.\`\\)`).exec(source);
  if (lazyAt === null) fail(`no lazy icon list (${lazy})`);
  const names = [...eager, ...lazyAt[1].split(".")];
  if (names.length < 100) fail(`only ${names.length} names; the bundle's shape has changed`);
  return names;
}

function render(names, version) {
  const lines = [];
  let line = " ";
  for (const name of names) {
    const item = ` "${name}",`;
    if (line.length + item.length > 110) {
      lines.push(line);
      line = " ";
    }
    line += item;
  }
  lines.push(line);
  return `// Generated by scripts/icon-names.mjs from bb ${version}'s app bundle; do not edit. Rerun it after a bb update.
//
// Every icon name bb's host Icon (experimental_Icon) can draw, in bb's own order: its eagerly bundled
// icons, then the ones it loads on first use. A name outside this list draws bb's generic bolt.

/** The bb version the list was read from. */
export const BB_ICON_NAMES_SOURCE = "bb ${version}";

export const BB_ICON_NAMES: readonly string[] = [
${lines.join("\n")}
];
`;
}

function main() {
  const [bundleArg, versionArg] = process.argv.slice(2);
  const bundle = bundleArg ?? defaultBundle();
  const version = versionArg ?? JSON.parse(readFileSync(join(BB_APP, "package.json"), "utf8")).version;
  const names = iconNames(readFileSync(bundle, "utf8"));
  const duplicates = names.filter((name, index) => names.indexOf(name) !== index);
  // bb's registry has two names for one glyph (ClosePluginPane, CloseThreadPane), which is fine; the same
  // name twice is not.
  if (duplicates.length > 0) fail(`duplicate names: ${duplicates.join(", ")}`);
  writeFileSync(OUT, render(names, version));
  console.log(`icon-names: ${names.length} names from bb ${version} → ${OUT}`);
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) main();
