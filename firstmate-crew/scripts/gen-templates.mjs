// Bundles templates/ into server/templates.generated.ts, so the server half needs no file access to
// find its templates: `bb plugin build` bundles one script and the plugin's own directory is not on
// offer at run time. Run with `npm run gen:templates` after any change under templates/.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const templates = join(root, "templates");
const output = join(root, "server", "templates.generated.ts");

const paths = readdirSync(templates, { withFileTypes: true, recursive: true })
  .filter((entry) => entry.isFile())
  .map((entry) => relative(templates, join(entry.parentPath, entry.name)).split("\\").join("/"))
  .sort();

const entries = paths.map((path) => `  ${JSON.stringify(path)}: ${JSON.stringify(readFileSync(join(templates, path), "utf8"))},`);

const source = `// Generated by \`npm run gen:templates\` from templates/. Do not edit it: change the template and run that again.

export const TEMPLATE_FILES: Readonly<Record<string, string>> = {
${entries.join("\n")}
};
`;

writeFileSync(output, source, "utf8");
console.log(`Wrote ${paths.length} templates to ${relative(root, output)}`);
