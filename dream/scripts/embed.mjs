// Writes the generated modules that carry files the plugin needs at run time, which the server and
// host bundles cannot read from the plugin's folder (bb builds them into its cache):
//
// - host/guard-source.ts — guard/guard.mjs, which the host writes next to each dream workspace;
// - server/dream-skill.ts — skills/dream/SKILL.md, the dream prompt the server renders.
//
// `npm run embed` after changing either; a test fails while the two disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);

function embed(source, target, name, note) {
  const text = readFileSync(fileURLToPath(new URL(source, root)), "utf8");
  const body = `// Generated by scripts/embed.mjs from ${source}; do not edit. ${note}\nexport const ${name} = ${JSON.stringify(text)};\n`;
  writeFileSync(fileURLToPath(new URL(target, root)), body);
}

embed("guard/guard.mjs", "host/guard-source.ts", "GUARD_SOURCE", "The host writes it out for each dream.");
embed("skills/dream/SKILL.md", "server/dream-skill.ts", "DREAM_SKILL", "The server renders the dream prompt from it.");
