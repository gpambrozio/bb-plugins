// Bundles content/ into server/content.generated.ts, so the server half needs no file access to find
// the session brief and PRINCIPLES.md: `bb plugin build` bundles one script and the plugin's own
// directory is not on offer at run time. Run with `npm run gen:content` after any change under content/.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const content = join(root, "content");
const output = join(root, "server", "content.generated.ts");

const paths = readdirSync(content).filter((name) => name.endsWith(".md")).sort();
const entries = paths.map((path) => `  ${JSON.stringify(path)}: ${JSON.stringify(readFileSync(join(content, path), "utf8"))},`);
const version = createHash("sha256").update(readFileSync(join(content, "brief.md"))).digest("hex").slice(0, 12);

const source = `// Generated by \`npm run gen:content\` from content/. Do not edit it: change the markdown and run that again.

export const CONTENT_FILES: Readonly<Record<string, string>> = {
${entries.join("\n")}
};

/** The first 12 hex digits of brief.md's SHA-256, stored on each session. */
export const BRIEF_VERSION = ${JSON.stringify(version)};
`;

writeFileSync(output, source, "utf8");
console.log(`Wrote ${paths.length} files to ${relative(root, output)}`);
