// Bundles wrapper/code-mode-wrapper.mjs into host/wrapper.generated.ts, so the host entry can write the
// file on each machine: `bb plugin build` bundles one script, and the plugin's own folder is not on
// offer at run time. Run with `npm run gen:wrapper` after any change to the wrapper;
// host/wrapper.test.ts fails while the two differ.
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const input = join(root, "wrapper", "code-mode-wrapper.mjs");
const output = join(root, "host", "wrapper.generated.ts");

const source = `// Generated by \`npm run gen:wrapper\` from wrapper/code-mode-wrapper.mjs. Do not edit it: change the
// wrapper and run that again.

export const WRAPPER_SOURCE: string = ${JSON.stringify(readFileSync(input, "utf8"))};
`;

writeFileSync(output, source, "utf8");
console.log(`Wrote ${relative(root, output)}`);
